/* Public Function Prototypes --------------------------------------------------------------------------------------- */

/**
 * @brief   Initialize the OLED display before other display functions are called.
 * @return  ESP_OK after initialization and clearing, otherwise an initialization or active-resource error.
 */
esp_err_t init_display(void);

/**
 * @brief   Draw one line of text on the specified display page.
 * @param   str Null-terminated text; at most 16 characters are displayed.
 * @param   page Display page index from 0 to 7.
 * @return  None.
 */
void display_text(const char *str, int page);

/**
 * @brief   Draw a complete 128 x 64 monochrome bitmap.
 * @param   bmp Pointer to 1024 bytes in the display buffer format.
 * @return  None.
 */
void display_bitmap(const uint8_t *bmp);

/**
 * @brief   Draw the status bar using the requested indicators.
 * @param   show_bluetooth Whether to show the Bluetooth indicator.
 * @param   show_loc_date Location, date, and time flags; shown only when equal to 0x07.
 * @param   show_telescope Whether to show the telescope indicator.
 * @return  None.
 */
void draw_status_bar(bool show_bluetooth, uint8_t show_loc_date, bool show_telescope);

/**
 * @brief   Play the OLED startup animation.
 * @return  None.
 */
void startup_animation(void);

/**
 * @brief   Redraw the current application state, or clear the screen when display output is disabled.
 * @return  None.
 */
void update_display_screen(void);

/**
 * @brief   Show an application error if the display is available and block the calling task indefinitely.
 * @param   error Application error code to display.
 * @return  None.
 */
void update_display_ERROR_screen(ErrorCode error);

