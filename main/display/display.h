/**
 * @brief   Application status messages shown on the OLED.
 */
typedef enum
{
    STATUS_TIME_SET,          /**< Time synchronized. */
    STATUS_LOCATION_SET,      /**< Observer location synchronized. */
    STATUS_OTHER_SETTINGS,    /**< Other settings received. */
    STATUS_DATE_SET,          /**< Date synchronized. */
    STATUS_AUTO_SYNC,         /**< Automatic synchronization completed. */
    STATUS_ALIGN_1_STAR,      /**< One-star alignment completed. */
    STATUS_ALIGN_2_STAR,      /**< Two-star alignment completed. */
    STATUS_GOTO_OBJECT,       /**< GoTo object mode. */
    STATUS_APP_JOYSTICK,      /**< App joystick mode. */
    STATUS_SKY_BOX_ASSIST,    /**< Skybox assist mode. */
    STATUS_ANALOG_JOYSTICK,   /**< Analog joystick mode. */
    STATUS_STANDALONE_MODE,   /**< Standalone mode. */
    STATUS_RELEASE_STEPPERS,  /**< Stepper motors released. */
    STATUS_BT_CONNECTED,      /**< Bluetooth connected. */
    STATUS_BT_NOT_CONNECTED,  /**< Bluetooth disconnected. */
    STATUS_SET_GEAR_RATIO,    /**< Gear ratios saved. */
    STATUS_JOYSTICK_CALIB,    /**< Joystick calibration completed. */
    STATUS_DIRECTION_CALIB,   /**< Motor direction calibration completed. */
    STATUS_FACTORY_RESET,     /**< Factory reset status. */
    STATUS_TRACKING_ON,       /**< Tracking active. */
    STATUS_IDLE,              /**< Telescope ready. */
    STATUS_PROCESSING,        /**< Command processing in progress. */
    STATUS_BACKLASH,          /**< Backlash calibration completed. */
    STATUS_HORIZ_LIMIT,       /**< Tracking stopped at the horizon limit. */
    STATUS_SOLAR_OBJ,         /**< Solar-system object visibility sent. */
    STATUS_STANDALONE_LOW,    /**< Standalone mode at low speed. */
    STATUS_STANDALONE_MEDIUM, /**< Standalone mode at medium speed. */
    STATUS_STANDALONE_HIGH,   /**< Standalone mode at high speed. */
    STATUS_UNKNOWN            /**< Unknown status message. */
} StatusMessage;

/**
 * @brief   Application error codes shown on the OLED.
 */
typedef enum
{
    ERROR_NONE,                   /**< No application error. */
    ERROR_UNKNOWN_COMMAND_ID,     /**< Unknown command identifier. */
    ERROR_UNEXPECTED_TERMINATION, /**< Unexpected main-loop termination. */
    ERROR_INVALID_COMMAND         /**< Invalid command. */
} ErrorCode;

